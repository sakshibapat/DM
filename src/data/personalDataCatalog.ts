export function getPersonalDataMetadata(dataName: string): PersonalDataMetadata {
  if (PERSONAL_DATA_CATALOG[dataName]) {
    return PERSONAL_DATA_CATALOG[dataName];
  }
  return {
    id: `pd-custom-${dataName.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
    name: dataName,
    classification: 'Confidential',
    riskLevel: 'Medium',
    isHighRisk: false,
    regulatoryTags: ['Custom PII'],
    description: 'Custom personal data entry',
  };
}
